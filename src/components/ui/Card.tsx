"use client";

import React from "react";
import { cn } from "@/lib/cn";

/* ─── shadcn-style Card primitives (no extra deps) ─── */

const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "rounded-xl border border-border bg-card text-fg shadow-sm transition-colors",
        className
      )}
      {...props}
    />
  )
);
Card.displayName = "Card";

